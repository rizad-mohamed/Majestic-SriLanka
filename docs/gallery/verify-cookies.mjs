import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge'});
const context=await browser.newContext();const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4327/tours/');
await page.locator('[data-cookie-banner]:visible').waitFor();
assert.equal(await page.locator('script[src*="googletagmanager"]').count(),0);
await page.screenshot({path:'docs/gallery/cookie-desktop.png'});
await page.getByRole('button',{name:'Reject optional',exact:true}).first().click();
assert.equal(await page.locator('[data-cookie-banner]').isVisible(),false);
assert.ok((await context.cookies()).some(c=>c.name==='majestic_consent'&&decodeURIComponent(c.value).includes('"analytics":false')));
await page.reload();assert.equal(await page.locator('[data-cookie-banner]').isVisible(),false);
await page.getByRole('button',{name:'Cookie Settings',exact:true}).click();
await page.locator('[data-cookie-analytics]').check();await page.getByRole('button',{name:'Save preferences',exact:true}).click();
assert.ok((await context.cookies()).some(c=>c.name==='majestic_consent'&&decodeURIComponent(c.value).includes('"analytics":true')));
await context.addCookies([{name:'_ga',value:'test',url:'http://127.0.0.1:4327/'}]);
await page.getByRole('button',{name:'Cookie Settings',exact:true}).click();await page.getByRole('button',{name:'Reject optional',exact:true}).last().click();
assert.equal((await context.cookies()).some(c=>c.name==='_ga'),false);
await context.clearCookies();await page.setViewportSize({width:390,height:844});await page.reload();await page.locator('[data-cookie-banner]:visible').waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'docs/gallery/cookie-mobile.png'});
assert.deepEqual(errors,[]);console.log('PASS: default blocking, reject, remembered choices, settings, acceptance, withdrawal/cookie cleanup and mobile layout');await browser.close();
